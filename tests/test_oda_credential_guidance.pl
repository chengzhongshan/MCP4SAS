#!/usr/bin/env perl
use strict;
use warnings;
use Test::More;
use File::Temp qw(tempdir);
use FindBin qw($Bin);
use IPC::Open3;
use Symbol qw(gensym);
my $home=tempdir(CLEANUP=>1);
local $ENV{HOME}=$home;
local $ENV{USERPROFILE}=$home;
local $ENV{SASPY_CFGNAME}='oda';
local $ENV{SASPY_ODA_AUTHKEY}='oda';
local $ENV{PIPELINE_SKIP_SAS_ODA_AUTH_BOOTSTRAP}=0;
local $ENV{PIPELINE_SAS_ODA_ACCOUNT}='';
local $ENV{PIPELINE_SAS_ODA_PASSWORD}='';
my $err=gensym;
my $pid=open3(my $in,my $out,$err,$^X,"$Bin/../run_sas_codes_or_files_in_ODA.pl",'--check-saspy-connection-only','--output-prefix',"$home/results");
close $in;
my $text=(do{local $/;<$out>}//'').(do{local $/;<$err>}//'');
waitpid($pid,0);
isnt($? >> 8,0,'missing credentials fail before a SAS submission');
like($text,qr/Credential file checked:/,'identifies checked credential location');
like($text,qr/Configure SAS ODA Login/,'offers editor command');
like($text,qr/--prompt-sas-oda-auth --check-sas-oda-login-only/,'offers private terminal recovery');
like($text,qr/new Cygwin home/i,'explains distinct homes');
like($text,qr/Do not put passwords in AI chat/,'keeps password entry private');
unlike($text,qr/--sas-oda-password/,'does not recommend exposing passwords as arguments');
ok(!-e "$home/.authinfo" && !-e "$home/_authinfo",'failure does not create a credential file');
done_testing;
