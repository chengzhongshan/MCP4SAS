#!/usr/bin/env perl
use strict; use warnings;
use FindBin qw($Bin);
use lib "$Bin/../MCPDeps";
use SAS_ODA_Runner;
use SAS_Source_Analysis;
use Test::More;
my $runner=bless {},'SAS_ODA_Runner';
my $code=$runner->_build_targeted_remote_macro_loader(['mIxEd_name']);
like($code,qr/wanted='mIxEd_name\.sas'/,'exact spelling preserved for first lookup');
like($code,qr/do phase=1 to 2/,'exact pass precedes case-insensitive pass');
like($code,qr/upcase\(trim\(entry\)\)=upcase\(trim\(wanted\)\)/,'case folding covers basename and extension');
like($code,qr/selected=candidate/,'actual directory entry retained for include');
like($code,qr/%include "%superq\(_pipeline_targeted_macro_path\)"/,'include uses resolved Linux spelling');
like($code,qr/if matches>1 then do/,'multiple case-folded candidates detected');
like($code,qr/ERROR: Ambiguous case-insensitive macro filename/,'ambiguity is an explicit error');
like($code,qr/selected=''; failed=1/,'ambiguous source is never selected');
like($code,qr/child=dopen\(fileref\)/,'directories named with .sas extension are excluded');
like($code,qr/rc=dclose\(handle\)/,'directory handle released');
like($code,qr/rc=filename\(dirref\)/,'directory fileref released');
like($code,qr/%local _pipeline_targeted_macro_path _pipeline_targeted_macro_error/,'resolution state is scoped to helper call');
like($code,qr/array roots\[2\].*\("&_home" "&_macro_home"\)/,'ordinary macro retains HOME-first priority');
is_deeply(SAS_Source_Analysis::analyze_source($code)->{findings},[],'generated loader has balanced SAS strings/comments');
my $del=$runner->_build_targeted_remote_macro_loader(['DEL_DIR_RECURSIVE']);
like($del,qr/wanted='Del_Dir_Recursive\.sas'/,'known source alias remains canonical');
like($del,qr/array roots\[2\].*\("&_macro_home" "&_home"\)/,'deletion macro retains Macros-first priority');
like($del,qr/%sysmacexist\(Del_Dir_Recursive\)/,'deletion macro availability check retained');
is($runner->_build_targeted_remote_macro_loader([]),'','no lookup for empty dependency list');
done_testing();
